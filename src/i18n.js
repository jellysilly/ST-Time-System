function detectLang() {
    let loc = '';
    try {
        const c = globalThis.SillyTavern?.getContext?.();
        loc = c?.getCurrentLocale?.() || globalThis.localStorage?.getItem('language') || globalThis.navigator?.language || '';
    } catch { /* нет окружения ST (тесты) */ }
    return /^ru/i.test(String(loc)) ? 'ru' : 'en';
}

/** Язык интерфейса: 'ru' или 'en'. */
export function uiLang() {
    let pref = 'auto';
    try { pref = globalThis.SillyTavern?.getContext?.()?.extensionSettings?.time_system?.uiLang ?? 'auto'; } catch { /* тесты */ }
    if (pref === 'ru' || pref === 'en') return pref;
    return globalThis.SillyTavern ? detectLang() : 'ru';
}

/** t('npc.deleteTitle', { name: 'Олег' }) → «Удалить Олег?» */
export function t(key, vars) {
    const lang = uiLang();
    const s = DICT[lang]?.[key] ?? DICT.ru[key] ?? key;
    if (!vars) return s;
    return s.replace(/\{(\w+)\}/g, (m, k) => (Object.prototype.hasOwnProperty.call(vars, k) ? String(vars[k]) : m));
}

